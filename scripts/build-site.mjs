import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { createHash } from 'node:crypto';

const root = fileURLToPath(new URL('../', import.meta.url));
const mode = process.argv[2];
if (!['demo', 'staging'].includes(mode)) throw new Error('Usage: node scripts/build-site.mjs demo|staging');
let config = {};
if (mode === 'staging') {
  const url = process.env.KARTU_SUPABASE_URL || '';
  const key = process.env.KARTU_SUPABASE_PUBLISHABLE_KEY || '';
  if (!/^https:\/\/[a-z0-9]{20}\.supabase\.co$/.test(url)) throw new Error('Set KARTU_SUPABASE_URL to the exact hosted project origin.');
  if (!/^sb_publishable_[A-Za-z0-9_-]+$/.test(key)) throw new Error('Use a Supabase publishable key; secret, service-role and legacy JWT keys are not accepted by this build.');
  config = {supabaseUrl:url, supabasePublishableKey:key};
}
const types = {'index.html':'text/html; charset=utf-8','app.js':'text/javascript; charset=utf-8','styles.css':'text/css; charset=utf-8','icon.svg':'image/svg+xml','manifest.webmanifest':'application/manifest+json'};
const assets = {};
for (const [name, type] of Object.entries(types)) assets['/'+name] = {type, body:await readFile(path.join(root,name),'utf8')};
assets['/config.js'] = {type:'text/javascript; charset=utf-8', body:`window.KARTU_CONFIG = ${JSON.stringify(config)};\n`};
const revision = createHash('sha256').update(JSON.stringify(assets)).digest('hex').slice(0,16);
const source = await readFile(path.join(root,'scripts/site-handler.mjs'),'utf8');
const out = path.join(root,'deployment/site');
await mkdir(path.join(out,'dist/server'),{recursive:true});
await mkdir(path.join(out,'worker'),{recursive:true});
await writeFile(path.join(out,'package.json'),JSON.stringify({private:true,type:'module'},null,2)+'\n');
const generated = `// Generated by scripts/build-site.mjs. Do not edit.\nconst assets = ${JSON.stringify(assets)};\nconst backendOrigin = ${JSON.stringify(config.supabaseUrl || '')};\nconst release = ${JSON.stringify({revision,mode})};\n${source}`;
await writeFile(path.join(out,'worker/index.js'),generated);
await writeFile(path.join(out,'dist/server/index.js'),generated);
await writeFile(path.join(out,'RELEASE.json'),JSON.stringify({revision,mode,files:Object.keys(assets)},null,2)+'\n');
console.log(`Built ${mode} release ${revision}; only ${Object.keys(assets).length} allowlisted browser assets included.`);
